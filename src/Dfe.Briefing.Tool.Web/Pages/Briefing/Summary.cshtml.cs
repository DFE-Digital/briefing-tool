using Dfe.Briefing.Tool.Application.Helpers;
using Dfe.Briefing.Tool.Application.Orchestrators.Interfaces;
using Dfe.Briefing.Tool.Application.Providers.Interfaces;
using Dfe.Briefing.Tool.Domain.ValueObjects;
using Dfe.Briefing.Tool.Web.Sanitization;
using Microsoft.AspNetCore.Mvc;
using System.Text.Json;
using System.Threading.Channels;

namespace Dfe.Briefing.Tool.Web.Pages.Briefing
{
    /// <summary>
    /// The last step: the person accepts the AI disclaimer and generates the Briefing Tool summary of the school or trust
    /// they confirmed. The briefing streams in through <see cref="OnGetStreamAsync"/>; <see cref="OnPostAsync"/> is the
    /// same without JavaScript.
    /// </summary>
    public class SummaryModel(IBriefingOrchestrator briefingOrchestrator, IBriefingSubjectFinder subjectFinder,
        ILogger<SummaryModel> logger) : SubjectPageModel(subjectFinder)
    {
        public const string DisclaimerNotAccepted = "Confirm you understand you need to apply professional judgement when using content generated by AI";

        [BindProperty]
        public bool AcceptDisclaimer { get; set; }

        public string? BriefingOutput { get; private set; }

        /// <summary>When <see cref="BriefingOutput"/> was generated, shown as the date of the last summary.</summary>
        public DateTime? GeneratedAt { get; private set; }

        public async Task<IActionResult> OnGetAsync(CancellationToken cancellationToken)
            => await LoadSubjectAsync(cancellationToken) ? Page() : RedirectToStart();

        public async Task<IActionResult> OnPostAsync(CancellationToken cancellationToken)
        {
            if (!await LoadSubjectAsync(cancellationToken))
                return RedirectToStart();

            if (!AcceptDisclaimer)
            {
                ModelState.AddModelError(nameof(AcceptDisclaimer), DisclaimerNotAccepted);
                return Page();
            }

            try
            {
                var result = await briefingOrchestrator.GetBriefing(Subject!.ToParameters(), cancellationToken: cancellationToken);
                BriefingOutput = BriefingHtmlSanitizer.Sanitize(result.Output);
                GeneratedAt = DateTime.Now;
            }
            catch (Exception ex) when (!cancellationToken.IsCancellationRequested)
            {
                logger.LogError(ex, "Failed to generate briefing for {SchoolOrTrustName}", Subject!.Name);
                // Not about a field, so it's shown in the error summary unlinked.
                ModelState.AddModelError(string.Empty, "Sorry, something went wrong generating this summary. Please try again.");
            }

            return Page();
        }

        /// <summary>
        /// Streams the briefing generation progress and final output to the client using Server-Sent Events (SSE).
        /// </summary>
        /// <remarks>
        /// Returns <see cref="EmptyResult"/> so the page isn't rendered after the stream: the response has started, so
        /// the layout couldn't set its headers.
        /// </remarks>
        public async Task<IActionResult> OnGetStreamAsync(CancellationToken cancellationToken)
        {
            await StreamBriefingAsync(cancellationToken);
            return new EmptyResult();
        }

        private async Task StreamBriefingAsync(CancellationToken cancellationToken)
        {
            Response.ContentType = "text/event-stream";
            Response.Headers.CacheControl = "no-cache";
            Response.Headers["X-Accel-Buffering"] = "no";

            // The name comes from the record, not the browser, so the briefing is always of the school or trust confirmed.
            if (!await LoadSubjectAsync(cancellationToken))
            {
                await WriteEventAsync("error-message", $"This {SubjectNoun} can't be found. Go back and search for it again.", cancellationToken);
                return;
            }

            var parameters = Subject!.ToParameters();
            var channel = Channel.CreateUnbounded<string>();
            var briefingTask = RunBriefingAsync(parameters, channel.Writer, cancellationToken);

            await foreach (var message in channel.Reader.ReadAllAsync(cancellationToken))
            {
                await WriteEventAsync("progress", message, cancellationToken);
            }

            try
            {
                var result = await briefingTask;
                if (result.Output is { } briefing && briefingOrchestrator.CanAddWebSearchFindings(briefing))
                {
                    var offer = new WebSearchRequest(parameters.SchoolUrnOrTrustTrn, parameters.SchoolOrTrustName, briefing, result.City);
                    await WriteEventAsync("web-search-offer", JsonSerializer.Serialize(offer, JsonSerializerHelper.JsonOptions), cancellationToken);
                }

                await WriteEventAsync("complete", BriefingHtmlSanitizer.Sanitize(result.Output) ?? string.Empty, cancellationToken);
            }
            catch (Exception ex) when (!cancellationToken.IsCancellationRequested)
            {
                logger.LogError(ex, "Failed to generate briefing for {SchoolOrTrustName}", parameters.SchoolOrTrustName);
                await WriteEventAsync("error-message", "Sorry, something went wrong generating this summary. Please try again.", cancellationToken);
            }
        }

        /// <summary>
        /// Runs the web search the person asked for after reading the briefing, and returns its findings alone, shown
        /// apart from the briefing. Only the web search agent runs - the browser sends back the briefing it was given as
        /// evidence, so this also works whichever server instance answers.
        /// </summary>
        public async Task<IActionResult> OnPostWebSearchAsync([FromBody] WebSearchRequest? request, CancellationToken cancellationToken)
        {
            if (request is null || string.IsNullOrWhiteSpace(request.SchoolUrnOrTrustTrn) || string.IsNullOrWhiteSpace(request.SchoolOrTrustName)
                || string.IsNullOrWhiteSpace(request.Briefing) || request.Briefing.Length > MaxBriefingCharacters
                || !briefingOrchestrator.CanAddWebSearchFindings(request.Briefing))
            {
                return BadRequest(new { error = "This summary can't be searched for more information. Generate it again and try once more." });
            }

            try
            {
                // The website comes from the school's or trust's record, not the browser. The type is the one chosen,
                // passed on in the page's URL.
                UrnOrTrn = request.SchoolUrnOrTrustTrn;
                var website = await LoadSubjectAsync(cancellationToken) ? Subject!.Website : null;

                var parameters = new BriefingParameters(request.SchoolUrnOrTrustTrn, request.SchoolOrTrustName, IsTrust);
                var result = await briefingOrchestrator.GetWebSearchFindings(parameters, request.Briefing, request.City, website, cancellationToken);
                return new JsonResult(new { html = BriefingHtmlSanitizer.Sanitize(result.Output, WebSearchReferenceIdPrefix) ?? string.Empty });
            }
            catch (Exception ex) when (!cancellationToken.IsCancellationRequested)
            {
                logger.LogError(ex, "Failed to search the web for {SchoolOrTrustName}", request.SchoolOrTrustName);
                return StatusCode(StatusCodes.Status500InternalServerError,
                    new { error = "Sorry, something went wrong searching the web. Your summary is unchanged - please try again." });
            }
        }

        // The web search findings sit under the briefing in one panel, so their references need ids of their own.
        private const string WebSearchReferenceIdPrefix = "web-reference";

        // A briefing is well under this; the limit stops an oversized request being sent to the web search agent.
        private const int MaxBriefingCharacters = 300_000;

        private async Task<AIResult> RunBriefingAsync(BriefingParameters parameters, ChannelWriter<string> writer,
            CancellationToken cancellationToken)
        {
            try
            {
                return await briefingOrchestrator.GetBriefing(parameters, new ChannelProgress(writer), cancellationToken);
            }
            finally
            {
                writer.TryComplete();
            }
        }

        private async Task WriteEventAsync(string eventName, string data, CancellationToken cancellationToken)
        {
            var payload = string.Join('\n', data.ReplaceLineEndings("\n").Split('\n').Select(line => $"data: {line}"));
            await Response.WriteAsync($"event: {eventName}\n{payload}\n\n", cancellationToken);
            await Response.Body.FlushAsync(cancellationToken);
        }

        /// <summary>
        /// Wraps a ChannelWriter to implement IProgress, allowing progress messages to be sent to the client via Server-Sent Events (SSE).
        /// </summary>
        /// <param name="writer">The channel writer to wrap.</param>
        private sealed class ChannelProgress(ChannelWriter<string> writer) : IProgress<string>
        {
            public void Report(string value) => writer.TryWrite(value);
        }
    }

    /// <summary>A briefing the person has asked to add web search findings to.</summary>
    public sealed record WebSearchRequest(string SchoolUrnOrTrustTrn, string SchoolOrTrustName, string Briefing, string? City);
}
